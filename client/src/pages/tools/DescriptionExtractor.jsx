  const [description, setDescription] = useState("");
  const [lastFormData, setLastFormData] = useState(null);
  const [videoInfo, setVideoInfo] = useState(null);
  const [noDescriptionFound, setNoDescriptionFound] = useState(false);

  // Local input state so the tool page can be typed into directly.
  const [inputValue, setInputValue] = useState(query || "");

  const autoGeneratedQuery = useRef("");
  const previousHeroQuery = useRef("");

  /* =========================================================
     EXTRACT DESCRIPTION
     ========================================================= */

  const handleGenerate = async (formData) => {
    try {
      setLoading(true);
      setLastFormData(formData);
      setDescription("");
      setVideoInfo(null);
      setNoDescriptionFound(false);

      const url = String(formData?.topic || "").trim();

      if (!url) {
        alert("Please enter a YouTube video URL.");
        return;
      }

      const response = await api.get("/youtube/description", {
        params: {
          url,
        },
      });

      if (response.data.success) {
        const data = response.data.data || {};
        const extractedDescription = String(
          data.description || ""
        ).trim();

        setVideoInfo({
          videoId: data.videoId || "",
          videoUrl: data.videoUrl || url,
          title: data.title || "",
          channelTitle: data.channelTitle || "",
          channelId: data.channelId || "",
        });

        setDescription(extractedDescription);

        if (!extractedDescription) {
          setNoDescriptionFound(true);
        }
      } else {
        setDescription("");
        alert(
          response.data.message ||
            "Failed to extract YouTube description"
        );
      }
    } catch (error) {
      console.error("DESCRIPTION EXTRACTOR ERROR:", error);
      console.error("RESPONSE:", error.response);
      console.error("REQUEST:", error.request);

      alert(
        error.response?.data?.message ||
          error.message ||
          "Failed to extract YouTube description"
      );

      setDescription("");
      setVideoInfo(null);
      setNoDescriptionFound(false);
    } finally {
      setLoading(false);
    }
  };

